import React, { useEffect, useState } from 'react';
import { Sparkles, X } from 'lucide-react';
import { Tender } from '../types';
import { apiJson, ApiError } from '../services/api';
import { formatTenderValue } from '../utils/formatters';
import type { TenderAnalysis } from '../services/tenderAnalysis';

interface Props {
  tender: Tender;
  onClose: () => void;
}

type State =
  | { kind: 'loading' }
  | { kind: 'ready'; analysis: TenderAnalysis; source: { provider: string; model: string }; disclaimer: string }
  | { kind: 'error'; message: string };

export const TenderAnalysisModal: React.FC<Props> = ({ tender, onClose }) => {
  const [state, setState] = useState<State>({ kind: 'loading' });

  useEffect(() => {
    let cancelled = false;
    const t: any = tender;
    apiJson('/api/ai/analyze-tender', {
      method: 'POST',
      body: JSON.stringify({
        tender: {
          title: tender.title,
          authority: tender.authority,
          portal: tender.portal,
          sector: tender.sector,
          currency: tender.currency,
          budget: tender.budget,
          submissionDeadline: tender.submissionDeadline,
          description: tender.description,
          scopeOfWork: tender.scopeOfWork,
          sourceUrl: t.sourceUrl || '',
        },
      }),
    })
      .then((res: any) => {
        if (!cancelled) setState({ kind: 'ready', analysis: res.analysis, source: res.source, disclaimer: res.disclaimer });
      })
      .catch((err: unknown) => {
        if (cancelled) return;
        const message = err instanceof ApiError ? err.message : 'AI analysis could not be loaded.';
        setState({ kind: 'error', message });
      });
    return () => {
      cancelled = true;
    };
  }, [tender]);

  const Section: React.FC<{ title: string; children: React.ReactNode }> = ({ title, children }) => (
    <section className="mt-5">
      <h3 className="text-xs font-extrabold uppercase tracking-wider text-stone-500">{title}</h3>
      <div className="mt-2 text-sm text-stone-800">{children}</div>
    </section>
  );

  return (
    <div className="fixed inset-0 z-50 flex items-end sm:items-center justify-center bg-black/40 p-0 sm:p-4" role="dialog" aria-modal="true" aria-label="AI tender analysis">
      <div className="w-full sm:max-w-2xl max-h-[90vh] overflow-y-auto rounded-t-2xl sm:rounded-2xl bg-white shadow-xl p-5 sm:p-6">
        <div className="flex items-start justify-between gap-3">
          <div className="min-w-0">
            <p className="text-[11px] font-bold text-[#3f5724] flex items-center gap-1.5"><Sparkles className="w-3.5 h-3.5" /> AI analysis</p>
            <h2 className="text-base font-extrabold text-stone-900 leading-snug">{tender.title}</h2>
          </div>
          <button onClick={onClose} aria-label="Close" className="p-2 rounded-full hover:bg-stone-100 shrink-0">
            <X className="w-4 h-4" />
          </button>
        </div>

        {state.kind === 'loading' && <p className="mt-6 text-sm text-stone-500">Analysing the notice text…</p>}

        {state.kind === 'error' && (
          <p className="mt-6 text-sm text-rose-700 bg-rose-50 border border-rose-200 rounded-xl p-3">{state.message}</p>
        )}

        {state.kind === 'ready' && (
          <>
            <p className="mt-3 text-[11px] text-stone-500">
              Generated by {state.source.provider} ({state.source.model}). {state.disclaimer}
            </p>

            <Section title="Summary">
              <p>{state.analysis.summary || 'No summary returned.'}</p>
            </Section>

            <Section title="Key dates">
              {state.analysis.keyDates.length ? (
                <ul className="space-y-1">
                  {state.analysis.keyDates.map((d, i) => (
                    <li key={i}><span className="font-bold">{d.label}:</span> {d.date}</li>
                  ))}
                </ul>
              ) : <p className="text-stone-500">Not stated in the notice.</p>}
            </Section>

            <Section title="Eligibility">
              {state.analysis.eligibility.length ? (
                <ul className="space-y-2">
                  {state.analysis.eligibility.map((e, i) => (
                    <li key={i} className="rounded-xl border border-stone-200 p-3">
                      <p className="font-bold">{e.criterion}</p>
                      <p>{e.requirement}</p>
                      {e.note && <p className="text-xs text-stone-500 mt-1">{e.note}</p>}
                    </li>
                  ))}
                </ul>
              ) : <p className="text-stone-500">No eligibility criteria found in the notice text.</p>}
            </Section>

            <Section title="Risks">
              {state.analysis.risks.length ? (
                <ul className="list-disc pl-5 space-y-1">{state.analysis.risks.map((r, i) => <li key={i}>{r}</li>)}</ul>
              ) : <p className="text-stone-500">None identified from the notice text.</p>}
            </Section>

            <Section title="Budget (estimate)">
              <div className="rounded-xl bg-stone-50 border border-stone-200 p-3 space-y-1">
                <p>
                  <span className="font-bold">Stated estimate in notice:</span>{' '}
                  {state.analysis.budget.statedEstimate
                    ? formatTenderValue(state.analysis.budget.statedEstimate, state.analysis.budget.currency as any)
                    : 'Not stated'}
                </p>
                <p>
                  <span className="font-bold">AI line-item total:</span>{' '}
                  {state.analysis.budget.modelEstimateTotal
                    ? formatTenderValue(state.analysis.budget.modelEstimateTotal, state.analysis.budget.currency as any)
                    : 'Not enough data to total'}
                </p>
                <p><span className="font-bold">Suggested contingency:</span> {state.analysis.budget.contingencyPct}%</p>
              </div>
              {state.analysis.budget.lineItems.length > 0 && (
                <ul className="mt-3 space-y-2">
                  {state.analysis.budget.lineItems.map((li, i) => (
                    <li key={i} className="rounded-xl border border-stone-200 p-3">
                      <div className="flex justify-between gap-3">
                        <p className="font-bold">{li.item}</p>
                        <p className="font-mono text-xs">{li.estimatedAmount !== null ? formatTenderValue(li.estimatedAmount, state.analysis.budget.currency as any) : 'No amount'}</p>
                      </div>
                      <p className="text-xs text-stone-600">Basis: {li.basis}</p>
                      <p className="text-xs text-stone-500">Assumption: {li.assumption}</p>
                    </li>
                  ))}
                </ul>
              )}
              {state.analysis.budget.notes && <p className="mt-2 text-xs text-stone-500">{state.analysis.budget.notes}</p>}
            </Section>

            <Section title="Data gaps">
              {state.analysis.dataGaps.length ? (
                <ul className="list-disc pl-5 space-y-1">{state.analysis.dataGaps.map((g, i) => <li key={i}>{g}</li>)}</ul>
              ) : <p className="text-stone-500">None listed.</p>}
            </Section>
          </>
        )}
      </div>
    </div>
  );
};
